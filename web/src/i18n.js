const LOCALES = { zh: 'zh-CN', en: 'en-US', ja: 'ja-JP', ko: 'ko-KR' }

export const LANGS = [
  { id: 'zh', label: '中文' },
  { id: 'en', label: 'English' },
  { id: 'ja', label: '日本語' },
  { id: 'ko', label: '한국어' },
]

// 语言检测: localStorage 手动选择优先, 否则按浏览器语言 (无匹配回退英语)
let lang = localStorage.getItem('np_lang') || ''
if (!dicts[lang]) {
  const nav = (navigator.language || '').toLowerCase()
  lang = nav.startsWith('zh') ? 'zh' : nav.startsWith('ja') ? 'ja' : nav.startsWith('ko') ? 'ko' : 'en'
}

export function getLang() { return lang }

export function setLang(l) {
  if (!dicts[l]) return
  lang = l
  localStorage.setItem('np_lang', l)
}

// locale 返回当前语言的 BCP47 locale (日期时间格式化用)
export function locale() { return LOCALES[lang] || 'en-US' }

// t 翻译 key, 支持 {var} 插值; 缺失时回退英语再回退 key 本身
export function t(key, vars) {
  let s = (dicts[lang] && dicts[lang][key]) ?? dicts.en[key] ?? key
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', String(vars[k]))
  return s
}
